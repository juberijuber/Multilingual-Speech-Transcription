"""
speech/mock_provider.py
————————————————————————
Mock speech provider for development and demo purposes.

⚠️  This provider does NOT perform real speech recognition.
    It returns clearly-labelled placeholder text so that the rest of the
    application (API, database, UI) can be tested without a real speech engine.
    The response is always marked is_mock=True.
"""

import asyncio
import random
from typing import Optional

from app.speech.base import BaseSpeechProvider, TranscriptionResult

_MOCK_TRANSCRIPTS = [
    "[DEMO MODE] आज मौसम बहुत अच्छा है। The weather today is really beautiful.",
    "[DEMO MODE] Speech recognition is working in demo mode. Real transcription requires Faster-Whisper.",
    "[DEMO MODE] नमस्ते! This is a multilingual demo. यह एक डेमो है।",
    "[DEMO MODE] Hello world — this text was generated by the mock speech provider.",
    "[DEMO MODE] Machine learning aur AI ke baare mein baat karte hain. Let us discuss ML and AI.",
]


class MockSpeechProvider(BaseSpeechProvider):
    """
    Returns clearly-labelled fake transcription text.
    Used when SPEECH_PROVIDER=mock or when faster-whisper is unavailable.
    """

    async def transcribe_audio(
        self,
        audio_bytes: bytes,
        *,
        language: Optional[str] = None,
        audio_format: str = "webm",
    ) -> TranscriptionResult:
        # Simulate a small processing delay
        await asyncio.sleep(0.5)

        transcript = random.choice(_MOCK_TRANSCRIPTS)

        return TranscriptionResult(
            transcript=transcript,
            language=language or "en",
            duration_seconds=round(len(audio_bytes) / 16000, 2) if audio_bytes else 0.0,
            provider="mock",
            is_mock=True,
        )
